const { Router } = require('express')
const controller = require('../controllers/recurringExpense.controller')
const validate = require('../middlewares/validate.middleware')
const { createRecurringExpenseSchema, updateRecurringExpenseSchema, recurringExpenseIdParamSchema, listRecurringExpensesQuerySchema, deleteRecurringExpenseSchema } = require('../schemas/recurringExpense.schema')
const router = Router()
router.get('/', validate(listRecurringExpensesQuerySchema, 'query'), controller.list)
router.get('/:id', validate(recurringExpenseIdParamSchema, 'params'), controller.getById)
router.get('/:id/deletion-preview', validate(recurringExpenseIdParamSchema, 'params'), controller.deletionPreview)
router.post('/', validate(createRecurringExpenseSchema, 'body'), controller.create)
router.put('/:id', validate(recurringExpenseIdParamSchema, 'params'), validate(updateRecurringExpenseSchema, 'body'), controller.update)
router.delete('/:id', validate(recurringExpenseIdParamSchema, 'params'), validate(deleteRecurringExpenseSchema, 'body'), controller.remove)
module.exports = router
